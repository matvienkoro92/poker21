const test=require('node:test'),assert=require('node:assert/strict');
const {messages}=require('../lib/club-week-deals');
const now=Date.parse('2026-11-29T21:00:00Z');
function deal(id,at){return {id,status:'confirmed',payer:{name:'A'},owner:{name:'B'},confirmedAt:at,currency:'usd',amountCents:10000};}
test('Sunday ends at Moscow midnight, split pages keep the day and credits count once',()=>{
  const first='2026-11-22T21:00:00Z',last='2026-11-29T20:59:59Z';
  const items=Array.from({length:14},(_,i)=>deal(String(i),first));
  items.push(deal('new',new Date(now).toISOString()),deal('old','2026-11-22T20:59:59Z'),{...deal('void',first),status:'voided'},deal('deposit-abc',last));
  const credits=[{id:'abc',clubId:'42',confirmedAt:Date.parse(last),amountCents:300000}];
  const clubs=new Map();
  const [week]=messages(items,credits,clubs,now,true);
  assert.match(week.text,/Сделок за неделю: 15/);
  assert.match(week.text,/1\s400,00 \$ \+ 3\s000,00 ₽/);
  assert.equal(week.reply_markup.inline_keyboard.length,7);
  const monday=week.reply_markup.inline_keyboard[0][0];
  assert.equal(monday.text,'Сделки понедельник');
  const start=Number(monday.callback_data.split(':')[1]);
  const [firstPage]=messages(items,credits,clubs,now,false,{start,day:0,page:0});
  assert.equal(firstPage.reply_markup.inline_keyboard.flat().filter(button=>button.url).length,12);
  const [secondPage]=messages(items,credits,clubs,now,false,{start,day:0,page:1});
  assert.match(secondPage.text,/13\. 00:00/);
  assert.match(secondPage.text,/14\. 00:00/);
  assert.doesNotMatch(secondPage.text,/23:59/);
  assert.equal(secondPage.reply_markup.inline_keyboard.at(-1)[0].callback_data,'weekdeals:'+start+':week');
  const [sunday]=messages(items,credits,clubs,now,false,{start,day:6,page:0});
  assert.match(sunday.text,/воскресенье · 29.11.2026/);
  assert.match(sunday.text,/1\. 23:59/);
  const [current]=messages(items,credits,clubs,now,false);
  assert.match(current.text,/30.11.2026 — 06.12.2026/);
  assert.match(current.text,/Сделок за неделю: 1/);
  assert.deepEqual(messages(items,credits,clubs,now,false,{start:start+1,day:0,page:0}),[]);
});
test('empty day opens from the week menu and can return',()=>{
  const [week]=messages([],[],new Map(),now,true);
  const start=Number(week.reply_markup.inline_keyboard[1][0].callback_data.split(':')[1]);
  const [day]=messages([],[],new Map(),now,false,{start,day:1,page:0});
  assert.match(day.text,/вторник · 24.11.2026/);
  assert.match(day.text,/Сделок нет/);
  assert.equal(day.reply_markup.inline_keyboard.length,1);
});
